"""Outline the bundled ZTV Han wordmark for Android TV launchers.

Requires fonttools, as does prepare-tv-fonts.py. No fonts are loaded at runtime
by the launcher; the approved brand PNG remains a separate drawable layer.
"""
from pathlib import Path
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
font = TTFont(root / "app/src/main/assets/fonts/ztv_han_medium.ttf")
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
scale = 32 / font["head"].unitsPerEm
advance = 0
paths = []
for character in "新蓝 TV":
    name = cmap[ord(character)]
    paths.append((name, advance))
    advance += font["hmtx"][name][0] * scale

bounds = BoundsPen(glyphs)
for name, offset in paths:
    glyphs[name].draw(TransformPen(bounds, (scale, 0, 0, -scale, offset, 0)))
_, top, _, bottom = bounds.bounds
baseline = (64 - (bottom - top)) / 2 - top
pen = SVGPathPen(glyphs, ntos=lambda value: format(value, ".3f").rstrip("0").rstrip("."))
for name, offset in paths:
    glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, offset, baseline)))
target = root / "app/src/main/res/drawable/tv_wordmark.xml"
target.write_text(
    '<?xml version="1.0" encoding="utf-8"?>\n'
    '<!-- Generated by tools/prepare-tv-wordmark.py from the bundled OFL font. -->\n'
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
    '    android:width="156dp" android:height="64dp"\n'
    '    android:viewportWidth="156" android:viewportHeight="64">\n'
    '    <path android:fillColor="#F4F1E8"\n'
    f'        android:pathData="{pen.getCommands()}" />\n'
    '</vector>\n'
)
print(target, "text width:", round(advance, 1))
